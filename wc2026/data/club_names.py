_SUFFIX = re.compile(r"\s+(FC|CF|SC|AFC|BC|SK|FK|CD|UD|AC|II)$")


def club_zh(name: str) -> str:
    """俱乐部英文名 → 中文；未命中回退英文原名。"""
    if not name:
        return name or ""
    if name in CLUB_ZH:
        return CLUB_ZH[name]
    stripped = _SUFFIX.sub("", name).strip()
    return CLUB_ZH.get(stripped, name)
